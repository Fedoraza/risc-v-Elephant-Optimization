###############################################################################
# void init_lfsr_bitsliced(uint32_t lfsr[7]);
#
# Initializes the 7-bit LFSR for Spongent-π[160] to:
#   lfsrIV = 0x75 = 0b1110101
#
# a0 = pointer to lfsr[7]
###############################################################################

    .section .text
    .globl init_lfsr_bitsliced
    .type  init_lfsr_bitsliced, @function

init_lfsr_bitsliced:
    ###########################################################################
    # bit 0 = 1
    ###########################################################################
    li      t0, -1              # 0xFFFFFFFF
    sw      t0, 0(a0)

    ###########################################################################
    # bit 1 = 0
    ###########################################################################
    sw      x0, 4(a0)

    ###########################################################################
    # bit 2 = 1
    ###########################################################################
    sw      t0, 8(a0)

    ###########################################################################
    # bit 3 = 0
    ###########################################################################
    sw      x0, 12(a0)

    ###########################################################################
    # bit 4 = 1
    ###########################################################################
    sw      t0, 16(a0)

    ###########################################################################
    # bit 5 = 1
    ###########################################################################
    sw      t0, 20(a0)

    ###########################################################################
    # bit 6 = 1
    ###########################################################################
    sw      t0, 24(a0)

    ret
